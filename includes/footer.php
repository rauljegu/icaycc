<script>

document.addEventListener('DOMContentLoaded', function () {

    /* =====================================================
       SUBMENÚS MULTINIVEL
       - Compatible con 2°, 3° y más niveles
       - Funciona por clic/touch
       - No cierra el menú padre al abrir un hijo
    ===================================================== */

    const submenuToggles = document.querySelectorAll(
        '.dropdown-submenu-toggle'
    );


    /* =====================================================
       CERRAR UN SUBMENÚ Y TODOS SUS HIJOS
    ===================================================== */

    function cerrarSubmenu(submenuItem) {

        submenuItem.classList.remove('is-open');
        submenuItem.classList.remove('submenu-left');

        const button = submenuItem.querySelector(
            ':scope > .dropdown-submenu-toggle'
        );

        if (button) {
            button.setAttribute(
                'aria-expanded',
                'false'
            );
        }

        /* Cerrar todos los submenús hijos */
        submenuItem
            .querySelectorAll('.dropdown-submenu.is-open')
            .forEach(function (child) {

                child.classList.remove('is-open');
                child.classList.remove('submenu-left');

                const childButton = child.querySelector(
                    ':scope > .dropdown-submenu-toggle'
                );

                if (childButton) {
                    childButton.setAttribute(
                        'aria-expanded',
                        'false'
                    );
                }

            });

    }


    /* =====================================================
       CERRAR SOLAMENTE LOS HERMANOS

       El padre permanece abierto.
       Esto permite:

       Vinculación y Educación Continua
                   ↓
               Vinculación
                   ↓
             tercer nivel
    ===================================================== */

    function cerrarHermanos(submenuItem) {

        const parentList = submenuItem.parentElement;

        if (!parentList) {
            return;
        }

        parentList
            .querySelectorAll(
                ':scope > .dropdown-submenu.is-open'
            )
            .forEach(function (sibling) {

                if (sibling !== submenuItem) {
                    cerrarSubmenu(sibling);
                }

            });

    }


    /* =====================================================
       DETERMINAR DIRECCIÓN DEL SUBMENÚ

       Escritorio:
       - Si cabe a la derecha → derecha
       - Si no cabe → izquierda
       - Si no cabe completamente en ningún lado,
         utiliza el lado con mayor espacio

       Móvil/tablet:
       - Siempre hacia abajo
    ===================================================== */

    function ajustarDireccion(submenuItem) {

        const menu = submenuItem.querySelector(
            ':scope > .dropdown-menu'
        );

        if (!menu) {
            return;
        }

        /* En móvil/tablet los submenús son verticales */
        if (window.innerWidth < 992) {

            submenuItem.classList.remove(
                'submenu-left'
            );

            return;
        }


        /*
         * Partimos de la posición derecha.
         */
        submenuItem.classList.remove(
            'submenu-left'
        );


        const rect =
            submenuItem.getBoundingClientRect();


        /*
         * Obtener el tamaño real del submenú.
         * Lo hacemos temporalmente visible sin mostrarlo
         * al usuario.
         */
        const oldDisplay = menu.style.display;
        const oldVisibility = menu.style.visibility;

        menu.style.visibility = 'hidden';
        menu.style.display = 'block';

        const menuWidth =
            menu.getBoundingClientRect().width;

        menu.style.display = oldDisplay;
        menu.style.visibility = oldVisibility;


        const espacioDerecha =
            window.innerWidth - rect.right;

        const espacioIzquierda =
            rect.left;


        /*
         * Si no cabe a la derecha y sí cabe a la izquierda,
         * abrir hacia la izquierda.
         */
        if (
            espacioDerecha < menuWidth &&
            espacioIzquierda >= menuWidth
        ) {

            submenuItem.classList.add(
                'submenu-left'
            );

            return;
        }


        /*
         * Si no cabe completamente a ninguno de los dos lados,
         * utilizar el lado que tenga más espacio.
         */
        if (
            espacioDerecha < menuWidth &&
            espacioIzquierda > espacioDerecha
        ) {

            submenuItem.classList.add(
                'submenu-left'
            );

        }

    }


    /* =====================================================
       ABRIR / CERRAR SUBMENÚ
    ===================================================== */

    submenuToggles.forEach(function (toggle) {

        toggle.addEventListener(
            'click',
            function (event) {

                event.preventDefault();
                event.stopPropagation();


                const submenuItem =
                    this.closest('.dropdown-submenu');


                if (!submenuItem) {
                    return;
                }


                const isOpen =
                    submenuItem.classList.contains(
                        'is-open'
                    );


                /*
                 * Si ya está abierto:
                 * cerrar este submenú y sus hijos.
                 */
                if (isOpen) {

                    cerrarSubmenu(
                        submenuItem
                    );

                    return;
                }


                /*
                 * Cerrar solamente los hermanos
                 * del mismo nivel.
                 */
                cerrarHermanos(
                    submenuItem
                );


                /*
                 * Abrir el actual.
                 */
                submenuItem.classList.add(
                    'is-open'
                );


                this.setAttribute(
                    'aria-expanded',
                    'true'
                );


                /*
                 * Decidir automáticamente si debe
                 * abrir hacia derecha o izquierda.
                 */
                ajustarDireccion(
                    submenuItem
                );

            }
        );

    });


    /* =====================================================
       CERRAR AL HACER CLICK FUERA DEL NAVBAR
    ===================================================== */

    document.addEventListener(
        'click',
        function (event) {

            if (
                !event.target.closest(
                    '.navbar-icaycc'
                )
            ) {

                document
                    .querySelectorAll(
                        '.dropdown-submenu.is-open'
                    )
                    .forEach(function (submenu) {

                        cerrarSubmenu(
                            submenu
                        );

                    });

            }

        }
    );


    /* =====================================================
       ESCAPE
    ===================================================== */

    document.addEventListener(
        'keydown',
        function (event) {

            if (event.key !== 'Escape') {
                return;
            }

            document
                .querySelectorAll(
                    '.dropdown-submenu.is-open'
                )
                .forEach(function (submenu) {

                    cerrarSubmenu(
                        submenu
                    );

                });

        }
    );


    /* =====================================================
       RECALCULAR DIRECCIÓN AL CAMBIAR EL TAMAÑO
       DE LA VENTANA
    ===================================================== */

    window.addEventListener(
        'resize',
        function () {

            document
                .querySelectorAll(
                    '.dropdown-submenu.is-open'
                )
                .forEach(function (submenu) {

                    ajustarDireccion(
                        submenu
                    );

                });

        }
    );

});

</script>


